#!/usr/bin/env python3
"""Shared verification of GitHub-hosted evidence for the pull-request review gate.

The gate counts a pull request as approved only when the mandated independent
reviewer posted a review on the pull request for the exact head SHA under
review. A durable receipt on its own is not evidence, because it is invisible
to anyone reading the pull request.

This module holds the single implementation of that check. It parses the
mandated review body and verifies a candidate review against the reviewed
head SHA, the durable review key, the reviewer model, and the recorded
verdict.

GitHub refuses an approving review on a pull request the connected identity
authored ("Can not approve your own pull request"). Reviews are posted
through the maintainer's connected identity, and the maintainer is often the
pull request author, so a comment review that states the verdict in its body
is accepted as gate evidence.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import urllib.error
import urllib.request
from typing import Any

MARKER = "Generated by independent OpenClaw Codex review"

# An approving review is impossible when the connected identity authored the
# pull request, so a comment review carrying the verdict is accepted too.
GITHUB_REVIEW_STATES = {"APPROVED", "COMMENTED"}

API_ROOT = "https://api.github.com"


def parse_review_body(body: str) -> dict[str, str]:
    """Extract the mandated markers from a posted review body."""
    text = (body or "").strip()
    fields = {
        "marker": "",
        "review_key": "",
        "head_sha": "",
        "model": "",
        "verdict": "",
    }
    lines = text.splitlines()
    if lines and lines[0].strip() == MARKER:
        fields["marker"] = MARKER
    for line in lines:
        key, sep, value = line.partition(":")
        if not sep:
            continue
        name = key.strip().lower()
        value = value.strip()
        if name == "durable review key":
            fields["review_key"] = value
        elif name in {"head sha", "reviewed head sha"}:
            fields["head_sha"] = value
        elif name == "model":
            fields["model"] = value
        elif name == "verdict":
            fields["verdict"] = value.lower()
    return fields


def verify_posted_review(
    reviews: list[dict[str, Any]],
    head_sha: str,
    review_key: str,
    verdict: str,
    model: str | None = None,
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Split candidate reviews into accepted evidence and rejected candidates.

    A review is accepted only when it is attached to the exact head SHA under
    review, carries the mandated marker and the durable review key of this
    handoff, states the expected verdict, and names the expected model.
    """
    accepted: list[dict[str, Any]] = []
    rejected: list[dict[str, Any]] = []
    for review in reviews:
        fields = parse_review_body(str(review.get("body") or ""))
        state = str(review.get("state") or "").upper()
        problems: list[str] = []
        if fields["marker"] != MARKER:
            problems.append("review body does not start with the mandated marker")
        if review_key and fields["review_key"] != review_key:
            problems.append("review body names a different durable review key")
        if fields["head_sha"] != head_sha:
            problems.append("review body names a different head SHA")
        if str(review.get("commit_id") or "") != head_sha:
            problems.append("review is attached to a different head SHA")
        if state not in GITHUB_REVIEW_STATES:
            problems.append(f"review state {state!r} is not gate evidence")
        if verdict and fields["verdict"] != verdict:
            problems.append(f"review verdict {fields['verdict']!r} does not match {verdict!r}")
        if model and fields["model"] != model:
            problems.append("review body names a different model")
        entry = {
            "id": review.get("id"),
            "state": state,
            "commit_id": review.get("commit_id"),
            "url": review.get("html_url"),
            "body": str(review.get("body") or ""),
            "submitted_at": review.get("submitted_at"),
            "user": (review.get("user") or {}).get("login"),
            "review_key": fields["review_key"],
            "head_sha": fields["head_sha"],
            "model": fields["model"],
            "verdict": fields["verdict"],
            "problems": problems,
        }
        (accepted if not problems else rejected).append(entry)
    return accepted, rejected


def find_review(reviews: list[dict[str, Any]], url: str) -> dict[str, Any] | None:
    """Return the review published at a URL, if the pull request has one."""
    if not url:
        return None
    for review in reviews:
        if review.get("html_url") == url:
            return review
    return None


def posting_evidence(
    reviews: list[dict[str, Any]],
    review_url: str,
    head_sha: str,
    review_key: str,
    verdict: str,
    model: str | None = None,
    repository: str = "",
    pr_number: int = 0,
) -> tuple[dict[str, Any] | None, list[str]]:
    """Verify the published review and build the durable posting record.

    The posting record is what the gate reads later, so it carries the facts
    GitHub reported rather than facts the reviewer claimed: the review id,
    its state, the commit it is attached to, and the body as published.
    """
    review = find_review(reviews, review_url)
    if review is None:
        return None, [f"no published review was found at {review_url!r}"]
    accepted, _ = verify_posted_review([review], head_sha, review_key, verdict, model)
    if not accepted:
        problems = accepted[0]["problems"] if accepted else []
        detail = problems or ["the published review is not acceptable gate evidence"]
        return None, detail
    fields = parse_review_body(str(review.get("body") or ""))
    evidence = {
        "repository": repository,
        "pr_number": pr_number,
        "commit_sha": review.get("commit_id"),
        "url": review.get("html_url"),
        "review_id": review.get("id"),
        "state": str(review.get("state") or "").upper(),
        "body": str(review.get("body") or ""),
        "submitted_at": review.get("submitted_at"),
        "user": (review.get("user") or {}).get("login"),
        "review_key": fields["review_key"],
        "head_sha": fields["head_sha"],
        "model": fields["model"],
        "verdict": fields["verdict"],
    }
    return evidence, []


def fetch_reviews(repository: str, pr_number: int) -> list[dict[str, Any]]:
    """Read the reviews attached to a pull request."""
    path = f"/repos/{repository}/pulls/{pr_number}/reviews?per_page=100"
    if shutil.which("gh"):
        result = subprocess.run(
            ["gh", "api", path],
            capture_output=True,
            text=True,
            check=False,
        )
        if result.returncode == 0:
            payload = json.loads(result.stdout or "[]")
            return payload if isinstance(payload, list) else []
    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    if not token:
        raise RuntimeError("no GitHub credential available to read pull request reviews")
    request = urllib.request.Request(
        f"{API_ROOT}{path}",
        headers={
            "Authorization": f"Bearer {token}",
            "Accept": "application/vnd.github+json",
            "User-Agent": "collatz-research-review-gate",
        },
    )
    with urllib.request.urlopen(request, timeout=60) as response:
        payload = json.loads(response.read().decode("utf-8"))
    return payload if isinstance(payload, list) else []
