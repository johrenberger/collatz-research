#!/usr/bin/env python3
"""Shared verification of GitHub-hosted evidence for the pull-request review gate.

The gate counts a pull request as approved only when the mandated independent
reviewer posted a review on the pull request for the exact head SHA under
review. A durable receipt on its own is not evidence, because it is invisible
to anyone reading the pull request.

This module holds the single implementation of that check. It parses the
mandated review body and verifies a candidate review against the reviewed
head SHA, the durable review key, the reviewer model, and the recorded
verdict.

GitHub refuses an approving review on a pull request the connected identity
authored ("Can not approve your own pull request"). Reviews are posted
through the maintainer's connected identity, and the maintainer is often the
pull request author, so a comment review that states the verdict in its body
is accepted as gate evidence.
"""

from __future__ import annotations

import json
import os
import shutil
import subprocess
import urllib.error
import urllib.request
from typing import Any

MARKER = "Generated by independent OpenClaw Codex review"

# An approving review is impossible when the connected identity authored the
# pull request, so a comment review carrying the verdict is accepted too.
GITHUB_REVIEW_STATES = {"APPROVED", "COMMENTED"}

API_ROOT = "https://api.github.com"


def parse_review_body(body: str) -> dict[str, str]:
    """Extract the mandated markers from a posted review body."""
    text = (body or "").strip()
    fields = {
        "marker": "",
        "review_key": "",
        "head_sha": "",
        "model": "",
        "verdict": "",
    }
    lines = text.splitlines()
    if lines and lines[0].strip() == MARKER:
        fields["marker"] = MARKER
    for line in lines:
        key, sep, value = line.partition(":")
        if not sep:
            continue
        name = key.strip().lower()
        value = value.strip()
        if name == "durable review key":
            fields["review_key"] = value
        elif name in {"head sha", "reviewed head sha"}:
            fields["head_sha"] = value
        elif name == "model":
            fields["model"] = value
        elif name == "verdict":
            fields["verdict"] = value.lower()
    return fields


def verify_posted_review(
    reviews: list[dict[str, Any]],
    head_sha: str,
    review_key: str,
    verdict: str,
    model: str | None = None,
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Split candidate reviews into accepted evidence and rejected candidates.

    A review is accepted only when it is attached to the exact head SHA under
    review, carries the mandated marker and the durable review key of this
    handoff, states the expected verdict, and names the expected model.
    """
    accepted: list[dict[str, Any]] = []
    rejected: list[dict[str, Any]] = []
    for review in reviews:
        fields = parse_review_body(str(review.get("body") or ""))
        state = str(review.get("state") or "").upper()
        problems: list[str] = []
        if fields["marker"] != MARKER:
            problems.append("review body does not start with the mandated marker")
        if review_key and fields["review_key"] != review_key:
            problems.append("review body names a different durable review key")
        if fields["head_sha"] != head_sha:
            problems.append("review body names a different head SHA")
        if str(review.get("commit_id") or "") != head_sha:
            problems.append("review is attached to a different head SHA")
        if state not in GITHUB_REVIEW_STATES:
            problems.append(f"review state {state!r} is not gate evidence")
        if verdict and fields["verdict"] != verdict:
            problems.append(f"review verdict {fields['verdict']!r} does not match {verdict!r}")
        if model and fields["model"] != model:
            problems.append("review body names a different model")
        entry = {
            "id": review.get("id"),
            "state": state,
            "commit_id": review.get("commit_id"),
            "url": review.get("html_url"),
            "body": str(review.get("body") or ""),
            "submitted_at": review.get("submitted_at"),
            "user": (review.get("user") or {}).get("login"),
            "review_key": fields["review_key"],
            "head_sha": fields["head_sha"],
            "model": fields["model"],
            "verdict": fields["verdict"],
            "problems": problems,
        }
        (accepted if not problems else rejected).append(entry)
    return accepted, rejected


def parse_review_url(url: str) -> tuple[str, int, int] | None:
    """Return (repository, pr_number, review_id) for a pull-request review URL.

    The URL binds the evidence to one pull request and one review, so a
    review published elsewhere cannot be offered as evidence for this head.
    """
    text = (url or "").strip()
    prefix = "https://github.com/"
    if not text.startswith(prefix):
        return None
    rest = text[len(prefix) :]
    path, _, fragment = rest.partition("#")
    parts = path.split("/")
    if len(parts) != 4 or parts[2] != "pull" or not parts[3].isdigit():
        return None
    repository = f"{parts[0]}/{parts[1]}"
    pr_number = int(parts[3])
    review_id = 0
    if fragment:
        marker = "pullrequestreview-"
        if not fragment.startswith(marker) or not fragment[len(marker) :].isdigit():
            return None
        review_id = int(fragment[len(marker) :])
    return repository, pr_number, review_id


def review_url_problems(
    url: str,
    repository: str = "",
    pr_number: int = 0,
    review_id: Any = None,
) -> list[str]:
    """Check that a review URL names the pull request and review it claims.

    A URL that names a different pull request, a different repository, or a
    different review is not evidence for this handoff, however well it is
    formatted.
    """
    parsed = parse_review_url(url)
    if parsed is None:
        return [f"{url!r} is not a pull-request review URL"]
    named_repository, named_pr, named_review = parsed
    problems: list[str] = []
    if repository and named_repository.lower() != repository.lower():
        problems.append(
            f"the review URL names repository {named_repository!r}, not {repository!r}"
        )
    if pr_number and named_pr != pr_number:
        problems.append(
            f"the review URL names pull request {named_pr}, not {pr_number}"
        )
    if review_id is not None and named_review != review_id:
        problems.append(f"the review URL names review {named_review}, not {review_id}")
    return problems


def find_review(reviews: list[dict[str, Any]], url: str) -> dict[str, Any] | None:
    """Return the review published at a URL, if the pull request has one."""
    if not url:
        return None
    for review in reviews:
        if review.get("html_url") == url:
            return review
    return None


def posting_evidence(
    reviews: list[dict[str, Any]],
    review_url: str,
    head_sha: str,
    review_key: str,
    verdict: str,
    model: str | None = None,
    repository: str = "",
    pr_number: int = 0,
) -> tuple[dict[str, Any] | None, list[str]]:
    """Verify the published review and build the durable posting record.

    The posting record is what the gate reads later, so it carries the facts
    GitHub reported rather than facts the reviewer claimed: the review id,
    its state, the commit it is attached to, and the body as published.
    """
    binding = review_url_problems(review_url, repository, pr_number)
    if binding:
        return None, binding
    review = find_review(reviews, review_url)
    if review is None:
        return None, [f"no published review was found at {review_url!r}"]
    bound = review_url_problems(review_url, repository, pr_number, review.get("id"))
    if bound:
        return None, bound
    accepted, rejected = verify_posted_review(
        [review], head_sha, review_key, verdict, model
    )
    if not accepted:
        detail = rejected[0]["problems"] if rejected else []
        return None, detail or ["the published review is not acceptable gate evidence"]
    fields = parse_review_body(str(review.get("body") or ""))
    evidence = {
        "repository": repository,
        "pr_number": pr_number,
        "commit_sha": review.get("commit_id"),
        "url": review.get("html_url"),
        "review_id": review.get("id"),
        "state": str(review.get("state") or "").upper(),
        "body": str(review.get("body") or ""),
        "submitted_at": review.get("submitted_at"),
        "user": (review.get("user") or {}).get("login"),
        "review_key": fields["review_key"],
        "head_sha": fields["head_sha"],
        "model": fields["model"],
        "verdict": fields["verdict"],
    }
    return evidence, []


def _fetch_review_page(
    repository: str, pr_number: int, page: int, per_page: int
) -> list[dict[str, Any]]:
    """Read one page of the reviews attached to a pull request."""
    path = (
        f"/repos/{repository}/pulls/{pr_number}/reviews"
        f"?per_page={per_page}&page={page}"
    )
    if shutil.which("gh"):
        result = subprocess.run(
            ["gh", "api", path],
            capture_output=True,
            text=True,
            check=False,
        )
        if result.returncode == 0:
            payload = json.loads(result.stdout or "[]")
            return payload if isinstance(payload, list) else []
    token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
    if not token:
        raise RuntimeError("no GitHub credential available to read pull request reviews")
    request = urllib.request.Request(
        f"{API_ROOT}{path}",
        headers={
            "Authorization": f"Bearer {token}",
            "Accept": "application/vnd.github+json",
            "User-Agent": "collatz-research-review-gate",
        },
    )
    with urllib.request.urlopen(request, timeout=60) as response:
        payload = json.loads(response.read().decode("utf-8"))
    return payload if isinstance(payload, list) else []


def fetch_reviews(
    repository: str,
    pr_number: int,
    per_page: int = 100,
    max_pages: int = 100,
) -> list[dict[str, Any]]:
    """Read every review attached to a pull request.

    GitHub paginates this listing, so one request sees only the first page:
    a review published after it would be invisible to the gate even though
    the evidence exists. Every page is read, and the walk stops when a page
    is short or repeats itself.
    """
    reviews: list[dict[str, Any]] = []
    seen: set[Any] = set()
    for page in range(1, max_pages + 1):
        batch = _fetch_review_page(repository, pr_number, page, per_page)
        if not batch:
            break
        fresh = [review for review in batch if review.get("id") not in seen]
        if not fresh:
            break
        seen.update(review.get("id") for review in fresh)
        reviews.extend(fresh)
        if len(batch) < per_page:
            break
    return reviews


def verified_posting_evidence(
    repository: str,
    pr_number: int,
    review_url: str,
    head_sha: str,
    review_key: str,
    verdict: str,
    model: str | None = None,
) -> tuple[dict[str, Any] | None, list[str]]:
    """Verify a claimed review against GitHub and return GitHub's own facts.

    The caller may only nominate a review; GitHub decides whether it exists,
    which head it is attached to, and what its body says. The returned
    record is built from GitHub's response, so a fabricated claim cannot
    become gate evidence.
    """
    binding = review_url_problems(review_url, repository, pr_number)
    if binding:
        return None, binding
    reviews = fetch_reviews(repository, pr_number)
    evidence, problems = posting_evidence(
        reviews,
        review_url,
        head_sha,
        review_key,
        verdict,
        model,
        repository,
        pr_number,
    )
    if evidence is None:
        return None, problems
    bound = review_url_problems(
        review_url, repository, pr_number, evidence.get("review_id")
    )
    if bound:
        return None, bound
    return evidence, []


def recorded_posting_problems(
    posting: dict[str, Any],
    head_sha: str,
    review_key: str,
    verdict: str,
    model: str | None = None,
    repository: str = "",
    pr_number: int = 0,
) -> list[str]:
    """Re-check recorded GitHub evidence against the receipt it must support.

    The evidence was verified against GitHub when it was recorded; this
    re-checks that the record still describes the review it names, so the
    gate does not count a record that was edited after the fact.
    """
    url = str(posting.get("url") or "")
    problems = review_url_problems(url, repository, pr_number, posting.get("review_id"))
    if problems:
        return problems
    review = {
        "id": posting.get("review_id"),
        "state": posting.get("state"),
        "commit_id": posting.get("commit_sha"),
        "html_url": url,
        "body": posting.get("body"),
    }
    accepted, rejected = verify_posted_review(
        [review], head_sha, review_key, verdict, model
    )
    if accepted:
        return []
    problems = []
    for entry in rejected:
        problems.extend(entry.get("problems") or [])
    return problems or ["the recorded GitHub review is not acceptable gate evidence"]
