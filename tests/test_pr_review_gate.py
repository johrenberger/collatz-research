"""Tests for the posted-GitHub-review requirement in the pull-request gate.

An approval counts only when the review is published on the pull request for
the exact head SHA under review, so these tests cover the parser, the
verifier, the ledger's fail-closed recording, and the dispatcher's refusal to
record an approval whose review was never published.
"""

from __future__ import annotations

import json
import os
import subprocess
import sys
from pathlib import Path

import pytest

REPO = Path(__file__).parents[1]
LIFECYCLE = REPO / "scripts" / "agent_lifecycle.py"
DISPATCHER = REPO / "scripts" / "dispatch_codex_pr_review.py"
EVIDENCE = REPO / "scripts" / "pr_review_evidence.py"

sys.path.insert(0, str(REPO / "scripts"))

from pr_review_evidence import (  # noqa: E402
    find_review,
    parse_review_body,
    posting_evidence,
    verify_posted_review,
)

REPOSITORY = "johrenberger/collatz-research"
PR_NUMBER = 7
HEAD = "a" * 40
REVIEW_KEY = "b" * 64
REVIEW_URL = f"https://github.com/{REPOSITORY}/pull/{PR_NUMBER}#pullrequestreview-42"


def _body(
    review_key: str = REVIEW_KEY,
    head_sha: str = HEAD,
    model: str = "openai/gpt-6.1-terra",
    verdict: str = "approved",
) -> str:
    return (
        "Generated by independent OpenClaw Codex review\n"
        "\n"
        f"Durable review key: {review_key}\n"
        f"Model: {model}\n"
        f"Head SHA: {head_sha}\n"
        f"Verdict: {verdict}\n"
    )


def _review(
    body: str | None = None,
    commit_id: str = HEAD,
    state: str = "COMMENTED",
    url: str = REVIEW_URL,
) -> dict[str, object]:
    return {
        "id": 42,
        "state": state,
        "commit_id": commit_id,
        "html_url": url,
        "body": _body() if body is None else body,
        "submitted_at": "2026-11-16T12:00:00Z",
        "user": {"login": "johrenberger"},
    }


def test_the_parser_reads_every_mandated_marker() -> None:
    fields = parse_review_body(_body())
    assert fields["marker"] == "Generated by independent OpenClaw Codex review"
    assert fields["review_key"] == REVIEW_KEY
    assert fields["head_sha"] == HEAD
    assert fields["model"] == "openai/gpt-6.1-terra"
    assert fields["verdict"] == "approved"


def test_a_published_review_for_the_exact_head_is_gate_evidence() -> None:
    accepted, rejected = verify_posted_review(
        [_review()], HEAD, REVIEW_KEY, "approved", "openai/gpt-6.1-terra"
    )
    assert rejected == []
    assert len(accepted) == 1
    assert accepted[0]["url"] == REVIEW_URL


def test_a_comment_review_counts_because_github_refuses_self_approval() -> None:
    accepted, _ = verify_posted_review([_review(state="COMMENTED")], HEAD, REVIEW_KEY, "approved")
    assert len(accepted) == 1


@pytest.mark.parametrize(
    ("review", "expected"),
    [
        (_review(commit_id="c" * 40), "attached to a different head SHA"),
        (_review(body=_body(head_sha="c" * 40)), "names a different head SHA"),
        (_review(body=_body(review_key="c" * 64)), "different durable review key"),
        (_review(body=_body(verdict="changes_requested")), "does not match"),
        (_review(body="just some text\n"), "mandated marker"),
        (_review(state="DISMISSED"), "not gate evidence"),
    ],
)
def test_a_review_that_is_not_bound_to_this_head_is_rejected(
    review: dict[str, object], expected: str
) -> None:
    accepted, rejected = verify_posted_review([review], HEAD, REVIEW_KEY, "approved")
    assert accepted == []
    assert any(expected in problem for problem in rejected[0]["problems"])


def test_posting_evidence_records_what_github_reported() -> None:
    evidence, problems = posting_evidence(
        [_review()],
        REVIEW_URL,
        HEAD,
        REVIEW_KEY,
        "approved",
        "openai/gpt-6.1-terra",
        REPOSITORY,
        PR_NUMBER,
    )
    assert problems == []
    assert evidence is not None
    assert evidence["commit_sha"] == HEAD
    assert evidence["url"] == REVIEW_URL
    assert evidence["review_key"] == REVIEW_KEY
    assert evidence["verdict"] == "approved"


def test_posting_evidence_fails_when_the_review_is_not_published() -> None:
    evidence, problems = posting_evidence(
        [], REVIEW_URL, HEAD, REVIEW_KEY, "approved", None, REPOSITORY, PR_NUMBER
    )
    assert evidence is None
    assert problems


def test_find_review_matches_the_published_url() -> None:
    assert find_review([_review()], REVIEW_URL) is not None
    assert find_review([_review()], "https://example.invalid/review/1") is None


def _run(state: Path, *args: str, expect: int = 0) -> dict[str, object]:
    result = subprocess.run(
        [
            sys.executable,
            str(LIFECYCLE),
            "--repo-path",
            str(REPO),
            "--state-dir",
            str(state),
            *args,
        ],
        text=True,
        capture_output=True,
    )
    assert result.returncode == expect, result.stderr
    return json.loads(result.stdout if expect == 0 else result.stderr)


def _request(state: Path, head_sha: str = HEAD) -> str:
    return str(
        _run(
            state,
            "request-review",
            "--repository",
            REPOSITORY,
            "--pr-number",
            str(PR_NUMBER),
            "--head-sha",
            head_sha,
            "--payload-json",
            "{}",
        )["review_key"]
    )


def _gate_status(state: Path) -> dict[str, object]:
    return _run(
        state,
        "gate-status",
        "--repository",
        REPOSITORY,
        "--pr-number",
        str(PR_NUMBER),
        "--head-sha",
        HEAD,
    )


def _approved_receipt(review_url: str | None) -> dict[str, object]:
    return {
        "repository": REPOSITORY,
        "pr_number": PR_NUMBER,
        "head_sha": HEAD,
        "round": 1,
        "model": "openai/gpt-6.1-terra",
        "verdict": "approved",
        "review_url": review_url,
        "findings": [],
    }


def test_recording_an_approval_without_a_published_review_is_refused(tmp_path: Path) -> None:
    state = tmp_path / "state"
    key = _request(state)
    error = _run(
        state,
        "record-review",
        "--review-key",
        key,
        "--receipt-json",
        json.dumps(_approved_receipt(None)),
        expect=2,
    )
    assert "posted GitHub review" in str(error["error"])


def test_recording_an_approval_with_a_published_review_is_accepted(tmp_path: Path) -> None:
    state = tmp_path / "state"
    key = _request(state)
    recorded = _run(
        state,
        "record-review",
        "--review-key",
        key,
        "--receipt-json",
        json.dumps(_approved_receipt(REVIEW_URL)),
    )
    assert recorded["decision"] == "review_recorded"


def test_a_changes_requested_verdict_needs_no_published_review(tmp_path: Path) -> None:
    state = tmp_path / "state"
    key = _request(state)
    receipt = _approved_receipt(None)
    receipt["verdict"] = "changes_requested"
    recorded = _run(
        state,
        "record-review",
        "--review-key",
        key,
        "--receipt-json",
        json.dumps(receipt),
    )
    assert recorded["decision"] == "review_recorded"


def test_the_gate_is_not_satisfied_until_the_review_is_published(tmp_path: Path) -> None:
    state = tmp_path / "state"
    key = _request(state)
    _run(
        state,
        "record-review",
        "--review-key",
        key,
        "--receipt-json",
        json.dumps(_approved_receipt(REVIEW_URL)),
    )
    status = _gate_status(state)
    assert status["gate_satisfied"] is False
    assert "no posted GitHub review" in status["reason"]

    posting = {
        "repository": REPOSITORY,
        "pr_number": PR_NUMBER,
        "commit_sha": HEAD,
        "url": REVIEW_URL,
        "review_id": 42,
        "state": "COMMENTED",
        "review_key": key,
        "verdict": "approved",
    }
    _run(state, "record-review-posting", "--review-key", key, "--posting-json", json.dumps(posting))
    status = _gate_status(state)
    assert status["gate_satisfied"] is True


def test_posting_evidence_bound_to_another_head_is_refused(tmp_path: Path) -> None:
    state = tmp_path / "state"
    key = _request(state)
    _run(
        state,
        "record-review",
        "--review-key",
        key,
        "--receipt-json",
        json.dumps(_approved_receipt(REVIEW_URL)),
    )
    posting = {
        "repository": REPOSITORY,
        "pr_number": PR_NUMBER,
        "commit_sha": "c" * 40,
        "url": REVIEW_URL,
        "review_key": key,
        "verdict": "approved",
    }
    error = _run(
        state,
        "record-review-posting",
        "--review-key",
        key,
        "--posting-json",
        json.dumps(posting),
        expect=2,
    )
    assert "different head SHA" in str(error["error"])


def _fake_gh(bin_dir: Path, reviews: list[dict[str, object]]) -> None:
    """Write a fake gh that answers the pull-request reviews query."""
    script = bin_dir / "gh"
    script.write_text(
        "#!/usr/bin/env python3\n"
        "import json, sys\n"
        f"REVIEWS = {json.dumps(reviews)}\n"
        "if 'reviews' in ' '.join(sys.argv):\n"
        "    sys.stdout.write(json.dumps(REVIEWS))\n"
        "else:\n"
        "    sys.stdout.write('{}')\n",
        encoding="utf-8",
    )
    script.chmod(0o755)


def _fake_openclaw(bin_dir: Path, receipt: dict[str, object]) -> None:
    script = bin_dir / "openclaw"
    script.write_text(
        "#!/usr/bin/env python3\n"
        "import json, sys\n"
        f"RECEIPT = {json.dumps(receipt)}\n"
        "sys.stdout.write(json.dumps({'text': json.dumps(RECEIPT)}))\n",
        encoding="utf-8",
    )
    script.chmod(0o755)


def test_the_dispatcher_refuses_an_approval_that_was_never_published(tmp_path: Path) -> None:
    state = tmp_path / "state"
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir(parents=True, exist_ok=True)
    receipt = _approved_receipt(REVIEW_URL)
    _fake_openclaw(bin_dir, receipt)
    _fake_gh(bin_dir, [])  # nothing was published

    key = _request(state)
    result = subprocess.run(
        [
            sys.executable,
            str(DISPATCHER),
            "--repo-path",
            str(REPO),
            "--state-dir",
            str(state),
            "--review-key",
            key,
        ],
        text=True,
        capture_output=True,
        env={**os.environ, "PATH": f"{bin_dir}{os.pathsep}{os.environ['PATH']}"},
    )
    assert result.returncode != 0
    assert "not gate evidence" in result.stderr

    ledger = json.loads((state / "turn-ledger.json").read_text(encoding="utf-8"))
    assert ledger["review_requests"][key]["status"] == "awaiting_review"


def test_the_dispatcher_records_the_published_review_as_gate_evidence(tmp_path: Path) -> None:
    state = tmp_path / "state"
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir(parents=True, exist_ok=True)
    key = _request(state)
    receipt = _approved_receipt(REVIEW_URL)
    _fake_openclaw(bin_dir, receipt)
    _fake_gh(bin_dir, [_review(body=_body(review_key=key))])

    result = subprocess.run(
        [
            sys.executable,
            str(DISPATCHER),
            "--repo-path",
            str(REPO),
            "--state-dir",
            str(state),
            "--review-key",
            key,
        ],
        text=True,
        capture_output=True,
        env={**os.environ, "PATH": f"{bin_dir}{os.pathsep}{os.environ['PATH']}"},
    )
    assert result.returncode == 0, result.stderr

    ledger = json.loads((state / "turn-ledger.json").read_text(encoding="utf-8"))
    entry = ledger["review_requests"][key]
    assert entry["status"] == "reviewed"
    assert entry["posting"]["url"] == REVIEW_URL
    assert entry["posting"]["commit_sha"] == HEAD
    assert entry["posting"]["review_key"] == key
